export type Messages = typeof en;

const catalogs: Record<Locale, Messages> = {
  'en-IN': en,
  // hi-IN reuses the en-IN shape; translations land here without touching components.
  'hi-IN': en,
};

export const locale: Locale = 'en-IN';
export const t: Messages = catalogs[locale];

export function srPowerTier(tier: PowerTier): string {
  return t.powerTiers[tier].toLowerCase();
}
